#!/usr/bin/env node
import { createHash } from "node:crypto";
import { spawn, execFile } from "node:child_process";
import { createServer } from "node:http";
import { mkdtemp, readFile, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createAgentSession } from "../lib/agent-session.mjs";

const option = (name, fallback) => { const i = process.argv.indexOf(name); return i < 0 ? fallback : process.argv[i + 1]; };
const space = Number(option("--ego-space", ""));
if(!Number.isInteger(space)||space<1)throw new Error("Pass --ego-space with the Agent-owned Space id created for this goal.");
const egoPage = option("--ego-page", "p1");
const samples = Number(option("--samples", "5"));
if(!Number.isInteger(samples)||samples<1||samples>25)throw new Error("samples must be 1–25");
const phase = option("--phase", "matched");
const root = fileURLToPath(new URL("..", import.meta.url));
const output = path.resolve(option("--output", `/tmp/brizo-ego-${phase}.json`));
const directory = await mkdtemp(path.join(os.tmpdir(), "brizo-bench-"));
const electron = option("--electron", undefined) || (await import("electron")).default;
const fixture = (await readFile(new URL("./fixtures/agent-workbench.html", import.meta.url), "utf8"))
  .replace('</script>', `if(new URLSearchParams(location.search).get('seed')==='ready'){q.value='Brizo';city.value='Shanghai';}</script>`);
const sourceFiles={};
for(const name of ["runtime/electron/agent-browser.mjs","runtime/electron/agent-session-tools.mjs","runtime/electron/agent-visual-input.mjs","runtime/electron/browser-command-agent.mjs","lib/agent-session.mjs","lib/client.mjs","lib/protocol.mjs"])sourceFiles[name]=createHash("sha256").update(await readFile(path.join(root,name))).digest("hex");
const fixtureHash=createHash("sha256").update(fixture).digest("hex");
const fixturePath = path.join(directory, "fixture.html");
await writeFile(fixturePath, fixture);
const server = createServer((_req, response) => { response.setHeader("Content-Type", "text/html; charset=utf-8"); response.end(fixture); });
await new Promise(resolve => server.listen(0, "127.0.0.1", resolve));
const egoURL = `http://127.0.0.1:${server.address().port}/`;
let host;
let hostMetadata;
const rows = [];
let session;
let round = 0;
const bytes = value => Buffer.byteLength(typeof value === "string" ? value : JSON.stringify(value));
// Each round gets a fresh file; only files generated by this run are executed.
async function egoRound(source) {
  const script = path.join(directory, `ego-round-${String(++round).padStart(3, "0")}.mjs`);
  await writeFile(script, source);
  const started = performance.now();
  const { stdout, stderr } = await new Promise((resolve, reject) => {
    const child = execFile("ego-browser", ["nodejs"], { timeout: 30000, maxBuffer: 4 * 1024 * 1024 }, (error, stdout, stderr) => error ? reject(Object.assign(error, {stdout,stderr})) : resolve({stdout,stderr}));
    child.stdin.end(source);
  });
  const line = `${stdout}\n${stderr}`.split("\n").find(line => line.startsWith("BENCH "));
  if (!line) throw new Error(`Ego round produced no result: ${stdout}\n${stderr}`);
  return { ...JSON.parse(line.slice(6)), invocationMs: performance.now() - started };
}
function egoScript(body) {
  return `const task = await taskSpace(${space}); const page = task.page(${JSON.stringify(egoPage)});\n${body}`;
}
const snapshotOptions = { scope: "full_page", includeActionMarks: false, includeStableLocator: false };
const observeOptions = phase === "baseline" ? {} : {format:"text"};
try {
  const initial = await egoRound(egoScript(`await page.goto(${JSON.stringify(egoURL)});
const initialSnapshot=await page.snapshot(${JSON.stringify(snapshotOptions)});
console.log("BENCH "+JSON.stringify({ ready: true, initialSnapshot, viewport: await page.evaluate(() => ({width:innerWidth,height:innerHeight,dpr:devicePixelRatio})), userAgent: await page.evaluate(() => navigator.userAgent) }));`));
  host = spawn(electron, [path.join(root, "scripts/agent-benchmark-host.mjs"), `--directory=${directory}`, `--fixture=${fixturePath}`, `--width=${initial.viewport.width}`, `--height=${initial.viewport.height}`], { cwd: root, stdio: ["ignore", "pipe", "pipe"] });
  hostMetadata = await new Promise((resolve, reject) => {
    let buffer = ""; let errors = "";
    const timer = setTimeout(() => reject(new Error(`Benchmark host did not become ready: ${errors}`)), 15000);
    host.stderr.on("data", chunk => { errors += chunk; });
    host.stdout.on("data", chunk => { buffer += chunk; for (const line of buffer.split("\n")) { try { const result = JSON.parse(line); if (result.ready) { clearTimeout(timer); resolve(result); } } catch {} } });
    host.once("exit", code => { clearTimeout(timer); reject(new Error(`Host exited ${code}: ${errors}`)); });
  });
  session = await createAgentSession({ goal: "Click Search, fill fields, and drag the card on the canvas", client: "benchmark", url: "https://fixture.brizo.example/", observe: observeOptions }, { clientOptions: { directory } });
  process.stdout.write(`${JSON.stringify({ phase, egoReady: initial.ready, viewport: initial.viewport, directory })}\n`);
  for (const scenario of option("--scenarios","observation,form,async-wait,canvas").split(",")) {
    for (let trial = 0; trial < samples; trial++) {
      // Alternate order across paired samples to limit warm-cache/order bias.
      for (const engine of trial % 2 ? ["ego", "brizo"] : ["brizo", "ego"]) {
        const seed = scenario === "async-wait" ? "?seed=ready" : "";
        let result;
        if (engine === "ego") {
          const prelude = `await page.goto(${JSON.stringify(egoURL + (seed ? seed+"&" : "?")+`round=${scenario}-${trial}`)});\nawait page.snapshot(${JSON.stringify(snapshotOptions)});\nconst started=performance.now();\nlet evidence;let apiCalls=0;let screenshots=[];\n`;
          let body;
          if (scenario === "observation") body = `evidence=await page.snapshot(${JSON.stringify(snapshotOptions)});apiCalls=1;`;
          if (scenario === "form") body = `await page.fill("loc=role:textbox[name='Search']","Brizo");await page.fill("loc=role:textbox[name='City']","Shanghai");await page.selectOption("select",{value:"newest"});await page.click("loc=role:button[name='Search']",{label:"search benchmark fixture"});await page.waitForFunction(()=>document.querySelector("#results").textContent==="Found Brizo in Shanghai (newest)",undefined,{timeout:3000});evidence=await page.snapshot(${JSON.stringify(snapshotOptions)});apiCalls=6;`;
          if (scenario === "async-wait") body = `await page.click("loc=role:button[name='Search']",{label:"wait for benchmark result"});await page.waitForFunction(()=>document.querySelector("#results").textContent==="Found Brizo in Shanghai (relevance)",undefined,{timeout:3000});evidence=await page.snapshot(${JSON.stringify(snapshotOptions)});apiCalls=3;`;
          if (scenario === "canvas") body = `screenshots.push(await page.screenshot());await page.mouse.move(70,300,{label:"start benchmark card drag"});await page.mouse.down();await page.mouse.move(220,350,{label:"move benchmark canvas card"});await page.mouse.up();await page.waitForFunction(()=>document.querySelector("#drag-status").textContent==="Card dragged",undefined,{timeout:3000});screenshots.push(await page.screenshot());evidence=await page.snapshot(${JSON.stringify(snapshotOptions)});apiCalls=8;`;
          result = await egoRound(egoScript(prelude + body + `\nconst elapsedMs=performance.now()-started;\nconst success=${scenario === "observation" ? 'String(evidence).includes("Item 59")' : scenario === "canvas" ? 'String(evidence).includes("Card dragged")' : `String(evidence).includes(${JSON.stringify(scenario === "form" ? "Found Brizo in Shanghai (newest)" : "Found Brizo in Shanghai (relevance)")})`};\nconsole.log("BENCH "+JSON.stringify({elapsedMs,outputBytes:Buffer.byteLength(typeof evidence==="string"?evidence:JSON.stringify(evidence)),success,apiCalls,screenshots}));`));
        } else {
          await session.act({ action: "navigate", url: `https://fixture.brizo.example/${seed ? seed+"&" : "?"}round=${scenario}-${trial}` }).catch(async error => { if (error.code) throw error; await session.observe(); throw error; });
          const started = performance.now();
          let evidence; let apiCalls; const screenshots = [];
          if (scenario === "observation") { evidence = await session.observe(observeOptions); apiCalls = 1; }
          if (scenario === "form") { const value = await session.batch([
            {action:"fill",target:{fieldName:"q"},value:"Brizo"},
            {action:"fill",target:{fieldName:"city"},value:"Shanghai"},
            {action:"select",target:{role:"combobox",name:"Sort"},value:"newest"},
            {action:"click",target:{role:"button",name:"Search"},wait:{text:"Found Brizo in Shanghai (newest)",timeoutMs:3000}},
          ],observeOptions); evidence=value.observation;apiCalls=1; }
          if (scenario === "async-wait") { const value=await session.act({action:"click",target:{role:"button",name:"Search"},wait:{text:"Found Brizo in Shanghai (relevance)",timeoutMs:3000},observe:observeOptions});evidence=value.observation;apiCalls=1; }
          let timings;
          if (scenario === "canvas") { const a=performance.now();screenshots.push(await session.screenshot(observeOptions));const b=performance.now();await session.act({action:"drag",from:{x:70,y:300},to:{x:220,y:350},wait:{text:"Card dragged",timeoutMs:3000}});const c=performance.now();screenshots.push(await session.screenshot(observeOptions));const d=performance.now();timings={beforeScreenshotMs:b-a,dragMs:c-b,afterScreenshotMs:d-c};evidence=session.observation;apiCalls=3; }
          const elapsedMs = performance.now() - started;
          const text = evidence.pageText;
          result = {elapsedMs,outputBytes:bytes(evidence),success:text.includes(scenario==="observation"?"Item 59":scenario==="canvas"?"Card dragged":scenario==="form"?"Found Brizo in Shanghai (newest)":"Found Brizo in Shanghai (relevance)"),apiCalls,screenshots,timings};
        }
        if(scenario === "canvas") {
          result.imageMetadata=[];
          for(const capture of result.screenshots){
            const png=await readFile(typeof capture==="string"?capture:capture.path);
            result.imageMetadata.push({pngWidth:png.readUInt32BE(16),pngHeight:png.readUInt32BE(20),...(typeof capture==="object"?{reported:capture.imageSize,scale:capture.imageScale,viewport:capture.viewport}:{})});
          }
          if(phase !== "baseline" && result.imageMetadata.some(image=>image.pngWidth !== initial.viewport.width || image.pngHeight !== initial.viewport.height)) throw new Error("Screenshot and viewport dimensions differ; discard this run.");
          result.screenshots=result.screenshots.map(capture=>typeof capture==="string"?capture:capture.path);
        }
        rows.push({engine,scenario,trial,...result});
        process.stdout.write(`${JSON.stringify({engine,scenario,trial,success:result.success,elapsedMs:Math.round(result.elapsedMs),outputBytes:result.outputBytes})}\n`);
        await writeFile(output,JSON.stringify({phase,egoSpace:space,egoPage,hostMetadata,egoMetadata:initial,fixturePath,fixtureHash,sourceFiles,rows},null,2)+"\n");
        if (!result.success) throw new Error(`${engine} ${scenario} failed`);
      }
    }
  }
} finally {
  await session?.finish("Completed fixed fixture benchmark",{keep:false}).catch(()=>{});
  host?.kill("SIGTERM");
  await new Promise(resolve=>{if(!host || host.exitCode!==null)return resolve();host.once("exit",resolve);const timer=setTimeout(()=>host.kill("SIGKILL"),3000);timer.unref();});
  server.closeAllConnections(); server.close();
}
